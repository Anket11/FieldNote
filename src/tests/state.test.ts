import assert from "node:assert/strict";
import test from "node:test";
import { DEMO_QUERY } from "../services/research";
import { makeStore } from "../store/store";
import { citationClosed, citationOpened, filtersChanged, packageSelectionChanged, queryChanged, requirementToggled, search, selectFilteredPackages, tabChanged } from "../store/researchSlice";

test("evidence open/close preserves tab, filters and selections; new searches reset result state", async () => {
  const store = makeStore();
  store.dispatch(queryChanged(DEMO_QUERY));
  await store.dispatch(search(DEMO_QUERY));
  const result = store.getState().research.result!;
  const id = result.packages[0].id;
  const requirement = result.items.find((item) => item.kind === "requirement")!;
  store.dispatch(packageSelectionChanged({ id, selected: true }));
  store.dispatch(packageSelectionChanged({ id, selected: true }));
  store.dispatch(requirementToggled(requirement.id));
  store.dispatch(tabChanged("packages"));
  store.dispatch(filtersChanged({ project: "P127974", review: "needs_review" }));
  store.dispatch(packageSelectionChanged({ id: "unknown", selected: true }));
  store.dispatch(requirementToggled("unknown"));
  store.dispatch(citationOpened("unknown"));
  assert.equal(store.getState().research.activeCitationId, null);
  const before = store.getState().research;
  store.dispatch(citationOpened(result.packages[0].citationIds[0]));
  assert.ok(store.getState().research.activeCitationId);
  store.dispatch(citationClosed());
  const after = store.getState().research;
  assert.equal(after.activeCitationId, null);
  assert.deepEqual(after.selectedPackageIds, [id]);
  assert.deepEqual(after.selectedRequirementIds, before.selectedRequirementIds);
  assert.deepEqual(after.filters, before.filters);
  assert.equal(after.activeTab, "packages");
  assert.equal(selectFilteredPackages(store.getState()).length, 3);
  store.dispatch(requirementToggled(requirement.id));
  store.dispatch(packageSelectionChanged({ id, selected: false }));
  assert.deepEqual(store.getState().research.selectedRequirementIds, []);
  assert.deepEqual(store.getState().research.selectedPackageIds, []);
  await store.dispatch(search(""));
  assert.equal(store.getState().research.query, DEMO_QUERY);
  assert.equal(store.getState().research.status, "error");
  assert.equal(store.getState().research.submittedQuery, DEMO_QUERY);
  await store.dispatch(search("unsupported"));
  assert.equal(store.getState().research.status, "empty");
  assert.equal(store.getState().research.result, null);
  assert.deepEqual(store.getState().research.filters, { project: "", review: "" });
  assert.equal(makeStore().getState().research.status, "idle");
});
