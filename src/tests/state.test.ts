import assert from "node:assert/strict";
import test from "node:test";
import { DEMO_QUERY } from "../services/research";
import { makeStore } from "../store/store";
import { citationClosed, citationOpened, projectFilterChanged, reviewSelectionChanged, queryChanged, evidenceOpened, search, selectFilteredPackages, selectPackageItems, selectPackageProjects, selectEvidenceCitations, tabChanged } from "../store/researchSlice";

test("project filters, package selection and both checklists survive evidence open/close", async () => {
  const store = makeStore();
  store.dispatch(queryChanged(DEMO_QUERY));
  await store.dispatch(search(DEMO_QUERY));
  const result = store.getState().research.result!;
  const candidate = selectPackageItems(store.getState())[0];
  const requirement = result.sections.find((section) => section.id === "tender_requirements")!.items[0];
  const readiness = result.sections.find((section) => section.id === "readiness_checklist")!.items[0];
  store.dispatch(reviewSelectionChanged({ id: candidate.id, selected: true }));
  store.dispatch(reviewSelectionChanged({ id: candidate.id, selected: true }));
  store.dispatch(reviewSelectionChanged({ id: requirement.id, selected: true }));
  store.dispatch(reviewSelectionChanged({ id: readiness.id, selected: true }));
  store.dispatch(tabChanged("prepare"));
  store.dispatch(projectFilterChanged("P127974"));
  const before = store.getState().research;
  store.dispatch(evidenceOpened({ itemId: requirement.id, openerId: "trigger" }));
  assert.ok(store.getState().research.activeCitationId);
  store.dispatch(citationClosed());
  const after = store.getState().research;
  assert.equal(after.activeCitationId, null);
  assert.deepEqual(after.selectedIds, [candidate.id, requirement.id, readiness.id]);
  assert.equal(after.projectFilter, before.projectFilter);
  assert.equal(after.activeTab, "prepare");
  assert.equal(selectPackageItems(store.getState()).length, 5);
  assert.equal(selectFilteredPackages(store.getState()).length, 3);
  assert.equal(selectPackageProjects(store.getState()).length, 2);

  store.dispatch(tabChanged("unknown"));
  store.dispatch(reviewSelectionChanged({ id: "similar_procurements:F4", selected: true }));
  store.dispatch(reviewSelectionChanged({ id: "overview:1", selected: true }));
  store.dispatch(citationOpened("toString"));
  assert.deepEqual(store.getState().research, after);
  store.dispatch(reviewSelectionChanged({ id: readiness.id, selected: false }));
  assert.deepEqual(store.getState().research.selectedIds, [candidate.id, requirement.id]);
  await store.dispatch(search(""));
  assert.equal(store.getState().research.query, DEMO_QUERY);
  assert.equal(store.getState().research.submittedQuery, DEMO_QUERY);
  assert.equal(store.getState().research.status, "error");
  await store.dispatch(search("unsupported"));
  assert.equal(store.getState().research.status, "empty");
  assert.equal(store.getState().research.result, null);
  assert.deepEqual(store.getState().research.selectedIds, []);
  assert.equal(store.getState().research.projectFilter, "");
  assert.equal(makeStore().getState().research.status, "idle");
});

test("evidence groups switch passages without changing work area or selections", async () => {
  const store = makeStore();
  await store.dispatch(search(DEMO_QUERY));
  const ids = ["cite_8fcf1ab7ffc626c2", "cite_c9f495a2bcd678f9"];
  store.dispatch(tabChanged("review"));
  store.dispatch(evidenceOpened({ itemId: "historical_awards:F2", openerId: "trigger" }));
  assert.deepEqual(selectEvidenceCitations(store.getState()).map((citation) => citation.id), ids);
  assert.equal(store.getState().research.activeCitationId, ids[0]);
  store.dispatch(citationOpened(ids[1]));
  assert.deepEqual(selectEvidenceCitations(store.getState()).map((citation) => citation.id), ids);
  assert.equal(store.getState().research.activeTab, "review");
  store.dispatch(citationClosed());
  assert.equal(store.getState().research.activeCitationId, null);
  assert.equal(store.getState().research.evidenceOpenerId, "trigger");
  assert.deepEqual(selectEvidenceCitations(store.getState()), []);
});
